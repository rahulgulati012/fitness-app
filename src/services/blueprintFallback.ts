interface RawDayTemplate {
  dayIndex: number;
  dayLabel: string;
  title: string;
  targetMuscle: string;
  durationMin: number;
  isRestDay: boolean;
  warmupTitle: string;
  warmupDrills: { name: string; prescription: string }[];
  exercises: {
    name: string;
    muscle: string;
    cue: string;
    tempo: string;
    restSeconds: number;
    setsCount: number;
    targetReps: number;
    suggestedWeightKg: number;
  }[];
}

function makeSets(setsCount: number, weightKg: number, reps: number, prefix: string): SetLog[] {
  return Array.from({ length: setsCount }, (_, i) => ({
    id: `${prefix}-s${i + 1}`,
    setNumber: i + 1,
    weightKg,
    reps,
    completed: false,
  }));
}

function hydrateSplit(rawDays: RawDayTemplate[]): WorkoutDay[] {
  return rawDays.map((d) => ({
    dayIndex: d.dayIndex,
    dayLabel: d.dayLabel,
    title: d.title,
    targetMuscle: d.targetMuscle,
    durationMin: d.durationMin,
    isRestDay: d.isRestDay,
    warmupTitle: d.warmupTitle,
    warmupDrills: d.warmupDrills.map((w, idx): WarmupDrill => ({
      id: `d${d.dayIndex}-w${idx}`,
      name: w.name,
      prescription: w.prescription,
      completed: false,
    })),
    exercises: d.exercises.map((e, idx): ExercisePlan => ({
      id: `d${d.dayIndex}-e${idx}`,
      name: e.name,
      muscle: e.muscle,
      cue: e.cue,
      tempo: e.tempo,
      restSeconds: e.restSeconds,
      sets: makeSets(e.setsCount, e.suggestedWeightKg, e.targetReps, `d${d.dayIndex}-e${idx}`),
    })),
  }));
}

